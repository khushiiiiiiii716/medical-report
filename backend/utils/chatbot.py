            response = "Based on your latest medical report, here are the parameters that are out of the optimal reference ranges:\n\n"
            for b in abnormalities:
                status_color = "🔴 High" if b["status"] == "High" else "🔵 Low" if b["status"] == "Low" else "🟡 Borderline"
                response += f"- **{b['name']}**: {b['value']} {b['unit']} ({status_color}, range: {b['reference_range']})\n  *What it means*: {b['description']}\n\n"
