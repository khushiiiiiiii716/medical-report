DISCLAIMER = "\n\n*Disclaimer: I am an AI Health Assistant, not a medical professional. This information is for educational purposes only and should not replace clinical diagnosis, advice, or treatment from a qualified doctor.*"

def process_chat_query(query, biomarkers=None, user_profile=None):
    """
    Processes a chat query about medical terms, lab results, and recommendations.
    Uses current report biomarkers and user profile for context.
    """
    query_lower = query.lower()
    
    # 1. Check if the user is asking about specific biomarkers in their report
    if biomarkers and ("my results" in query_lower or "my report" in query_lower or "abnormal" in query_lower or "wrong" in query_lower):
        abnormalities = [b for b in biomarkers if b["status"] in ["High", "Low", "Borderline"]]
        if not abnormalities:
            response = "I've reviewed your latest medical report, and all extracted health biomarkers look **Normal**! Keep up the excellent work with your healthy habits. Is there a specific parameter you would like me to explain?"
