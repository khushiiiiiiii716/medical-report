def get(lang, key, fallback=None):
    """Get a translated string for the given language and key."""
    lang = lang if lang in TRANSLATIONS else "en"
    return TRANSLATIONS[lang].get(key, fallback or TRANSLATIONS["en"].get(key, key))


def translate_status(status, lang):
    """Translate biomarker status strings."""
    status_map = {
        "Normal": "status_normal",
        "High": "status_high",
        "Low": "status_low",
        "Borderline": "status_borderline",
    }
    key = status_map.get(status)
    return get(lang, key) if key else status


def translate_category(category, lang):
    """Translate biomarker category strings."""
    cat_map = {
        "Complete Blood Count": "cat_cbc",
        "Blood Sugar": "cat_sugar",
        "Lipid Profile": "cat_lipid",
        "Thyroid Profile": "cat_thyroid",
        "Renal Profile": "cat_renal",
        "Cardiovascular": "cat_cardio",
    }
    key = cat_map.get(category)
    return get(lang, key) if key else category


def translate_biomarker(biomarker_dict, lang):
    """Translate status and category fields of a biomarker dict."""
    b = dict(biomarker_dict)
    b["status"] = translate_status(b.get("status", "Normal"), lang)
    b["category"] = translate_category(b.get("category", ""), lang)
    return b


