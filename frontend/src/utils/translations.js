export function useTranslation(lang = 'en') {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return (key, params = {}) => {
    let value = dict[key] || TRANSLATIONS.en[key] || key;
    Object.entries(params).forEach(([name, replaceValue]) => {
      value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replaceValue));
    });
    return value;
  };
}
